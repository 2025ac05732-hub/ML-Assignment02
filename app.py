# Pre-calculate performance metrics for all 5 requested models
@st.cache_resource
def compute_all_metrics(_models, _X_train, _X_test, _y_train, _y_test):
    results = {}
    for name, model in _models.items():
        # Fit model
        model.fit(_X_train, _y_train)
        # Predictions
        preds = model.predict(_X_test)

        # Handle binary vs multiclass for AUC
        unique_classes = np.unique(_y_test)
        if len(unique_classes) == 2:
            probs = model.predict_proba(_X_test)[:, 1]
            auc = roc_auc_score(_y_test, probs)
            precision = precision_score(_y_test, preds, zero_division=0)
            recall = recall_score(_y_test, preds, zero_division=0)
            f1 = f1_score(_y_test, preds, zero_division=0)
        else:
            probs = model.predict_proba(_X_test)
            auc = roc_auc_score(_y_test, probs, multi_class='ovr', average='macro')
            precision = precision_score(_y_test, preds, average='macro', zero_division=0)
            recall = recall_score(_y_test, preds, average='macro', zero_division=0)
            f1 = f1_score(_y_test, preds, average='macro', zero_division=0)

        acc = accuracy_score(_y_test, preds)
        mcc = matthews_corrcoef(_y_test, preds)

        results[name] = {
            "Accuracy": round(acc, 4),
            "AUC": round(auc, 4),
            "Precision": round(precision, 4),
            "Recall": round(recall, 4),
            "F1": round(f1, 4),
            "MCC": round(mcc, 4),
            "predictions": preds,
            "fitted_model": model
        }
    return results

